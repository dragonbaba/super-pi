import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, realpathSync } from "node:fs";
import { isAbsolute, join, relative, resolve, sep } from "node:path";

/** Cold measurement provenance. No symlinked dist artifact is silently followed. */
export function captureBuiltArtifacts(project) {
  const files = [], pending = [[join(project, "packages"), false]];
  while (pending.length) {
    const [directory, built] = pending.pop();
    for (const entry of readdirSync(directory, { withFileTypes: true })) {
      if (entry.name === "node_modules" || entry.name === ".git") continue;
      const path = join(directory, entry.name), included = built || entry.name === "dist";
      if (entry.isSymbolicLink()) { assert.equal(included, false, `Unbound symlinked build artifact: ${path}`); continue; }
      if (entry.isDirectory()) pending.push([path, included]);
      else if (built) {
        assert.equal(entry.isFile(), true, path);
        const bytes = readFileSync(path);
        files.push({ path: relative(project, path).split(sep).join("/"), bytes: bytes.length, sha256: createHash("sha256").update(bytes).digest("hex") });
      }
    }
  }
  files.sort(compareArtifacts);
  assert.ok(files.length > 0, "No built artifacts found");
  return { lockfileSha256: createHash("sha256").update(readFileSync(join(project, "package-lock.json"))).digest("hex"),
    files, sha256: createHash("sha256").update(JSON.stringify(files)).digest("hex") };
}
function compareArtifacts(left, right) { return left.path < right.path ? -1 : left.path > right.path ? 1 : 0; }

/** Bind the actual post-npm-ci install, including native/generated bytes and links.
 * SRI is verified by the preceding clean npm ci, not by hashing unpacked files.
 * Workspace links are recorded, not followed; their source/dist are bound separately.
 */
export function captureInstalledDependencies(project) {
  project = realpathSync(project);
  const lockBytes = readFileSync(join(project, "package-lock.json")), lock = JSON.parse(lockBytes);
  assert.equal(lock.lockfileVersion, 3); assert.ok(lock.packages);
  const files = [], packages = [], roots = new Set([join(project, "node_modules")]);
  for (const [path, expected] of Object.entries(lock.packages)) {
    if (!path) continue;
    const installed = resolve(project, path);
    assertInside(project, installed);
    if (!path.startsWith("node_modules/") && !path.includes("/node_modules/")) {
      const nested = join(installed, "node_modules"); if (existsSync(nested)) roots.add(nested);
      continue;
    }
    if (!existsSync(installed)) {
      assert.ok(expected.optional || expected.extraneous, `Required installed dependency missing: ${path}`);
      packages.push({ path, optionalAbsent: expected.optional === true, extraneousAbsent: expected.extraneous === true }); continue;
    }
    if (expected.link) {
      assert.equal(realpathSync(installed), realpathSync(resolve(project, expected.resolved)), `Unexpected workspace link: ${path}`);
      continue;
    }
    assert.ok(typeof expected.integrity === "string" && expected.integrity.length > 0, `Missing lock integrity: ${path}`);
    const actual = JSON.parse(readFileSync(join(installed, "package.json")));
    assert.equal(actual.version, expected.version, `Installed version differs from lock: ${path}`);
    packages.push({ path, name: actual.name, version: actual.version, resolved: expected.resolved, integrity: expected.integrity });
  }
  for (const root of roots) {
    assert.ok(existsSync(root), `Installed dependency root missing: ${root}`);
    const pending = [root];
    while (pending.length) {
      const directory = pending.pop();
      for (const entry of readdirSync(directory, { withFileTypes: true })) {
        const path = join(directory, entry.name), key = relative(project, path).split(sep).join("/");
        if (entry.isSymbolicLink()) {
          const target = realpathSync(path); assertInside(project, target);
          files.push({ path: key, link: relative(project, target).split(sep).join("/") });
        } else if (entry.isDirectory()) pending.push(path);
        else {
          assert.equal(entry.isFile(), true, path); const bytes = readFileSync(path);
          files.push({ path: key, bytes: bytes.length, sha256: createHash("sha256").update(bytes).digest("hex") });
        }
      }
    }
  }
  files.sort(compareArtifacts); packages.sort(compareArtifacts);
  return { lockfileSha256: createHash("sha256").update(lockBytes).digest("hex"), packages, files,
    sha256: createHash("sha256").update(JSON.stringify({ packages, files })).digest("hex") };
}
function assertInside(project, path) {
  const key = relative(project, path); assert.ok(key !== ".." && !key.startsWith(".." + sep) && !isAbsolute(key), `Dependency escapes project: ${path}`);
}
